export const LANGUAGES = { it: 'Italiano', en: 'English', de: 'Deutsch' };
const LOCALES = { it: 'it-IT', en: 'en-GB', de: 'de-DE' };

let lang = 'it';

export function detectLang() {
  const code = (navigator.language || 'it').slice(0, 2);
  return dict[code] ? code : 'it';
}

export function setLang(code) {
  lang = dict[code] ? code : 'it';
  document.documentElement.lang = lang;
}

export const locale = () => LOCALES[lang];

export function t(key, vars = {}) {
  const text = dict[lang][key] ?? dict.it[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}
